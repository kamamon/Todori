/* 年（1914.5＝1914年7〜9月）→ 四半期の番号 */
function fdQy(yf) { return Math.round((yf - G.y0) * 4); }
/* 補正を足す。k：dem 需要 / cost 材料 / cap 生産の能力 / tariff 関税（%の足し算） / credit 借りられる額 / rate 金利 / rival 外国の会社の売りやすさ / jpPen 日本製品への反感 / pcap 公定の値段 / pfloor 下限の値段 / quota 輸出の枠 / access 地域に入れる度合い */
function fdM(k, cat, r, v, from, to, why, x) { const m = Object.assign({ k, cat, r, v, from: fdQy(from), to: fdQy(to), why }, x || {}); G.mods.push(m); return m; }
/* 場所の名前で工場を探して被害を与える */
function fdDamageAt(locs, frac, why) {
  let hit = 0;
  for (const f of G.facs.filter(x => x.r === 'jp' && x.ready <= G.q + 4)) {
    if (!locs.some(l => (f.loc || '').includes(l) || (f.n || '').includes(l))) continue;
    fdDamageFac(f, clamp(frac * uni(0.75, 1.25), 0.05, 0.9), why);
    hit++;
  }
  return hit;
}
/* 去年の、その地域への輸出の台数（分野ごと） */
